"""Pre-render the weather icon font to PNG for the Kindle page.

The old Kindle browser renders @font-face fonts unreliably (missing digits and
icons), while system fonts and images render fine. So the page uses no web fonts:
text uses the system font, and the icons are images.

Inputs:
- vendor/weathericons/font/weathericons-regular-webfont.ttf  the glyphs
- vendor/weathericons/css/weather-icons.css                  moon/sun glyph codes
- css/custom-icons.css                                       OpenWeather id -> glyph code
Outputs:
- images/icons/{day,night}/<code>.png
- images/icons.js  (var weatherIcons = {day, night, moon, sunrise, sunset})

Run from the repository root:
    uv run --no-project --python 3.14 --with pillow python tools/build_images.py
"""

from pathlib import Path
import json
import re

from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent.parent  # repository root
out = root / "images"
icon_font_path = root / "vendor" / "weathericons" / "font" / "weathericons-regular-webfont.ttf"

ICON_EM = 128   # px font size for the icons
ICON_BOX = 200  # px square canvas: every weathericons glyph fits within ±100px (1.5625em)
INK = {"day": 0, "night": 255}  # black icons on the white page, white on the night page

# The 28 moon phase images in phase order, starting at new moon.
MOON = (["wi-moon-alt-new"]
        + ["wi-moon-alt-waxing-crescent-%d" % i for i in range(1, 7)]
        + ["wi-moon-alt-first-quarter"]
        + ["wi-moon-alt-waxing-gibbous-%d" % i for i in range(1, 7)]
        + ["wi-moon-alt-full"]
        + ["wi-moon-alt-waning-gibbous-%d" % i for i in range(1, 7)]
        + ["wi-moon-alt-third-quarter"]
        + ["wi-moon-alt-waning-crescent-%d" % i for i in range(1, 7)])

rule = re.compile(r"\.(wi-[a-z0-9-]+):before\s*\{\s*content:\s*\"\\(f[0-9a-f]+)\"", re.I)


def css_map(path):
    return {name: code.lower() for name, code in rule.findall(path.read_text(encoding="utf-8"))}


base = css_map(root / "vendor" / "weathericons" / "css" / "weather-icons.css")
owm = css_map(root / "css" / "custom-icons.css")


def glyph(name):
    if name not in base:
        raise ValueError("Icon not found in weather-icons.css: " + name)
    return base[name]


icons = {"day": {}, "night": {}}
for name, code in owm.items():
    match = re.fullmatch(r"wi-owm-(day|night)-(\d+)", name)
    if match:
        icons[match.group(1)][match.group(2)] = code
icons["moon"] = [glyph(name) for name in MOON]
icons["sunrise"] = glyph("wi-sunrise")
icons["sunset"] = glyph("wi-sunset")

codes = sorted(set(icons["day"].values()) | set(icons["night"].values()) | set(icons["moon"])
               | {icons["sunrise"], icons["sunset"]})

# Draw every glyph on the same em-square canvas with the same anchor, so relative
# size and position match the original font rendering. The background is
# transparent (grayscale + alpha): icon boxes overlap neighbouring text and the
# moon icons are rotated, so an opaque square would cover the text around them.
icon_font = ImageFont.truetype(str(icon_font_path), ICON_EM)
clipped = []
for mode, ink in INK.items():
    folder = out / "icons" / mode
    folder.mkdir(parents=True, exist_ok=True)
    for code in codes:
        coverage = Image.new("L", (ICON_BOX, ICON_BOX), 0)
        draw = ImageDraw.Draw(coverage)
        center = (ICON_BOX / 2, ICON_BOX / 2)
        box = draw.textbbox(center, chr(int(code, 16)), font=icon_font, anchor="mm")
        if box[0] < 0 or box[1] < 0 or box[2] > ICON_BOX or box[3] > ICON_BOX:
            clipped.append(code)
        draw.text(center, chr(int(code, 16)), font=icon_font, fill=255, anchor="mm")
        img = Image.new("LA", (ICON_BOX, ICON_BOX), (ink, 0))
        img.putalpha(coverage)
        img.save(folder / (code + ".png"), optimize=True)

(out / "icons.js").write_text(
    "// Generated by tools/build_images.py. Glyph codes of images/icons/<day|night>/<code>.png:\n"
    "// day/night by OpenWeather condition id, moon by phase (28 steps from new moon), sunrise, sunset.\n"
    "var weatherIcons = " + json.dumps(icons, sort_keys=True, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)

total = sum(p.stat().st_size for p in out.rglob("*.png"))
print(f"{len(icons['day'])} day + {len(icons['night'])} night ids, 28 moon phases -> {len(codes)} glyphs")
print(f"clipped icons: {sorted(set(clipped)) or 'none'}")
print(f"total PNG size: {total // 1024} KB")
